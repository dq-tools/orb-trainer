def damage_candidates(temp, skill='たたく'):
    """温度と特技からダメージ候補7通りを返す。温度は50℃刻みに丸める。"""
    t = max(50, min(2000, int(temp) // 50 * 50))
    return DAMAGE_TABLE[t][SKILL_MULTIPLIER[skill]]


def damage_range(temp, skill='たたく'):
    """(最小, 最大) ダメージを返す。"""
    c = damage_candidates(temp, skill)
    return c[0], c[-1]
